#!/usr/bin/env python3
"""Regenerate the browser build's copy of the game.

The playable page on GitHub Pages is served from ``docs/`` only, so the real
game sources have to travel with it. This script packs ``main.py`` and every
``kreml/**.py`` file into one generated script, ``docs/play/game_bundle.js``,
which the page writes into Pyodide's in-memory filesystem.

Run it after touching the game:

    python tools/build_web.py            # rewrite the bundle
    python tools/build_web.py --check    # exit 1 if the bundle is stale

``tests/test_web_build.py`` runs the same check, so a forgotten rebuild fails
the test suite instead of shipping a page that plays last week's game.
"""
from __future__ import annotations

import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "play" / "game_bundle.js"
HEADER = ("/* Generated by tools/build_web.py — do not edit by hand.\n"
          "   Every file below is a byte-for-byte copy of the game's source. */\n")


def source_files() -> list[pathlib.Path]:
    files = [REPO / "main.py"]
    files.extend(sorted((REPO / "kreml").rglob("*.py")))
    return [f for f in files if f.is_file()]


def bundle_text() -> str:
    payload = {}
    for path in source_files():
        rel = path.relative_to(REPO).as_posix()
        payload["/game/" + rel] = path.read_text(encoding="utf-8")
    body = json.dumps(payload, ensure_ascii=False, indent=1, sort_keys=True)
    return HEADER + "self.KREML_BUNDLE = " + body + ";\n"


def main(argv: list[str]) -> int:
    text = bundle_text()
    if "--check" in argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print("stale: run `python tools/build_web.py`", file=sys.stderr)
            return 1
        print(f"web bundle up to date ({len(text) / 1024:.0f} KB)")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO).as_posix()} "
          f"({len(source_files())} files, {len(text) / 1024:.0f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
